import AppKit
import os

/// Marks pasteboard contents written by this app (skipped by clipboard history).
public enum OwnMarker {
    public static let type = NSPasteboard.PasteboardType("com.emojipicker.own")
}

/// A full copy of every type's data of every item on a pasteboard.
public struct PasteboardSnapshot: Sendable {
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let log = Logger(subsystem: "com.emojipicker.app", category: "pasteboard")

    private let items: [[NSPasteboard.PasteboardType: Data]]

    init(items: [[NSPasteboard.PasteboardType: Data]]) {
        self.items = items.filter { !$0.isEmpty }
    }

    /// True if any item carries a sensitive marker (e.g. a password manager's copy).
    public var containsSensitiveTypes: Bool {
        items.contains { Self.isSensitive(types: Array($0.keys), includeOwnMarker: false) }
    }

    /// Types that mark an item as secret, generated or short-lived: the nspasteboard.org markers
    /// plus the private ones some password managers and clipboard tools set.
    public static let sensitiveTypes: Set<NSPasteboard.PasteboardType> = [
        concealedType,
        transientType,
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
        NSPasteboard.PasteboardType("com.typeit4me.clipping"),
        NSPasteboard.PasteboardType("Pasteboard generator type"),
        NSPasteboard.PasteboardType("net.antelle.keeweb"),
    ]

    /// The one place that decides whether a pasteboard item's type list marks it as secret
    /// (see `sensitiveTypes`) or, with `includeOwnMarker`, as written by this app.
    public static func isSensitive(types: [NSPasteboard.PasteboardType], includeOwnMarker: Bool = true) -> Bool {
        types.contains { sensitiveTypes.contains($0) || (includeOwnMarker && $0 == OwnMarker.type) }
    }

    public static func capture(_ pb: NSPasteboard) -> PasteboardSnapshot {
        let items = (pb.pasteboardItems ?? []).map { item in
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) {
                    dict[type] = data
                } else {
                    log.info("dropping pasteboard type with no data: \(type.rawValue, privacy: .public)")
                }
            }
            return dict
        }
        return PasteboardSnapshot(items: items)
    }

    public func restore(to pb: NSPasteboard) {
        pb.clearContents()
        let objects: [NSPasteboardItem] = items.map { dict in
            let item = NSPasteboardItem()
            for (type, data) in dict { item.setData(data, forType: type) }
            return item
        }
        if !objects.isEmpty, !pb.writeObjects(objects) {
            Self.log.error("failed to restore \(objects.count) pasteboard item(s)")
        }
    }
}

/// Restore the user's clipboard only if nobody has touched it since we wrote our payload.
public func shouldRestore(currentChangeCount: Int, ourChangeCount: Int) -> Bool {
    currentChangeCount == ourChangeCount
}
